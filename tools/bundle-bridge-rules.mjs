#!/usr/bin/env node
/**
 * The bridge's rules, compiled in (0.141.18, NBA Live's security check 11/21: the bridge downloaded oddlines.js and
 * linerare.js from beside the ?cc= address and ran them with new Function, so a link could run outside code inside NBA
 * Live). The modules are copied into docs/bridge/cc-bridge.js between the BUNDLED RULES markers, each wrapped in a
 * function that returns its exports; nothing is downloaded and run any more. 0.142: src/records/featlive.js too (FEAT_RULES).
 *   node tools/bundle-bridge-rules.mjs          rewrite the block from src/situations/{oddlines,linerare}.js and src/records/featlive.js
 *   node tools/bundle-bridge-rules.mjs --check  exit 1 if the block differs from what the sources would give
 * Run it after changing any of them (a test fails until it is run).
 */
import fs from "node:fs";

const root = new URL("..", import.meta.url).pathname;
const BRIDGE = root + "docs/bridge/cc-bridge.js";
const START = "  // ===== BUNDLED RULES: generated by tools/bundle-bridge-rules.mjs from src/situations/oddlines.js, linerare.js and src/records/featlive.js. Edit those, then run the tool. =====";
const END = "  // ===== END BUNDLED RULES =====";

export function bundle(oddSrc, rareSrc, featSrc = null) {
  const wrap = (name, src) => {
    const names = [];
    const body = String(src).replace(/^export (const|function) ([A-Za-z_$][\w$]*)/gm, (_, kind, n) => { names.push(n); return `${kind} ${n}`; });
    if (/^\s*(import|export)\b/m.test(body)) throw new Error(`${name}: an import or export the bundler can't take`);
    return `  var ${name} = (function () {\n${body.replace(/\s+$/, "")}\n    return { ${names.join(", ")} };\n  })();`;
  };
  return [START, wrap("ODD_RULES", oddSrc), wrap("RARE_RULES", rareSrc), ...(featSrc != null ? [wrap("FEAT_RULES", featSrc)] : []), END].join("\n");
}
export function currentBlock(text) {
  const a = text.indexOf(START), b = text.indexOf(END);
  return a >= 0 && b > a ? text.slice(a, b + END.length) : null;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const want = bundle(fs.readFileSync(root + "src/situations/oddlines.js", "utf8"), fs.readFileSync(root + "src/situations/linerare.js", "utf8"), fs.readFileSync(root + "src/records/featlive.js", "utf8"));
  const text = fs.readFileSync(BRIDGE, "utf8"), have = currentBlock(text);
  if (process.argv.includes("--check")) { console.log(have === want ? "bundled rules: up to date" : "bundled rules: OUT OF DATE (run node tools/bundle-bridge-rules.mjs)"); process.exit(have === want ? 0 : 1); }
  if (!have) throw new Error("no BUNDLED RULES block in the bridge");
  fs.writeFileSync(BRIDGE, text.replace(have, want));
  console.log(`bundled rules written (${want.split("\n").length} lines)`);
}
