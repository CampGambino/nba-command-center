import pandas as pd, numpy as np
df = pd.read_pickle("lines.pkl")
for c in ["min","pts","fgm","fga","fg3m","fg3a","ftm","fta","oreb","dreb","reb","ast","stl","blk","tov","pf"]: df[c] = df[c].fillna(0).astype(int)
df["grp"] = df.pos.map(lambda p: "G" if p in ("G","PG","SG") else "C" if p=="C" else "F")
df["other"] = df.reb+df.ast+df.stl+df.blk
df.to_pickle("lines2.pkl")
S = df.season.nunique(); recent = df[df.season>=2021]
def show(name, m, sort=None, asc=False, n=3):
    x = df[m]; r = recent[m[recent.index]]
    ex = (x.sort_values(sort, ascending=asc) if sort else x.sort_values("d", ascending=False)).head(n)
    line = "; ".join(f"{e['name'].strip(chr(34))} {e.d} ({e.pts} pts {e.fgm}-{e.fga} FG {e.ftm}-{e.fta} FT {e.reb}r {e.ast}a {e['min']}m)" for _,e in ex.iterrows())
    print(f"{name}: {len(x)} in {S} seasons ({len(x)/S:.1f}/season; last five {len(r)/5:.1f}/season) | {line}")
show("0 FGM on 10+ FGA", (df.fgm==0)&(df.fga>=10), "fga")
show("0 FGM on 12+ FGA", (df.fgm==0)&(df.fga>=12), "fga")
show("0-for-8+ from three", (df.fg3m==0)&(df.fg3a>=8), "fg3a")
show("0-for-10+ from three", (df.fg3m==0)&(df.fg3a>=10), "fg3a")
show("10+ pts with 0 FGM", (df.fgm==0)&(df.pts>=10), "pts")
show("20+ pts on 2 or fewer FGM", (df.fgm<=2)&(df.pts>=20), "pts")
show("FTA 20+", (df.fta>=20), "fta")
show("FT points 75%+ of 15+ pts", (df.pts>=15)&(df.ftm>=0.75*df.pts), "pts")
show("35+ pts, 0 FTA", (df.pts>=35)&(df.fta==0), "pts")
show("40+ pts, 0 FTA", (df.pts>=40)&(df.fta==0), "pts")
show("30+ pts, 0 FTA", (df.pts>=30)&(df.fta==0), "pts")
show("25+ pts, 0 reb/ast/stl/blk", (df.pts>=25)&(df.other==0), "pts")
show("20+ pts, 0 reb/ast/stl/blk", (df.pts>=20)&(df.other==0), "pts")
show("30+ pts, 1 or fewer reb+ast+stl+blk", (df.pts>=30)&(df.other<=1), "pts")
show("15+ pts in 10 or fewer min", (df.pts>=15)&(df['min']<=10)&(df['min']>0), "pts")
show("20+ pts in 15 or fewer min", (df.pts>=20)&(df['min']<=15)&(df['min']>0), "pts")
show("guard with 15+ reb", (df.grp=="G")&(df.reb>=15), "reb")
show("guard with 18+ reb", (df.grp=="G")&(df.reb>=18), "reb")
show("center with 12+ ast", (df.grp=="C")&(df.ast>=12), "ast")
show("center with 5+ threes", (df.grp=="C")&(df.fg3m>=5), "fg3m")
show("guard with 6+ blocks", (df.grp=="G")&(df.blk>=6), "blk")
td = ((df.pts>=10).astype(int)+(df.reb>=10)+(df.ast>=10)+(df.stl>=10)+(df.blk>=10))
show("triple-double under 10 pts", (td>=3)&(df.pts<10), "pts", True)
show("10+ reb and 10+ ast, under 10 pts", (df.reb>=10)&(df.ast>=10)&(df.pts<10), "pts", True)
show("double-double with 0-2 pts", (((df.reb>=10).astype(int)+(df.ast>=10)+(df.blk>=10)+(df.stl>=10))>=2)&(df.pts<=2), "pts", True)
show("exactly 1 of pts/reb/ast/stl/blk/tov", (df.pts==1)&(df.reb==1)&(df.ast==1)&(df.stl==1)&(df.blk==1)&(df.tov==1))
show("exactly 1 of pts/reb/ast/stl/blk", (df.pts==1)&(df.reb==1)&(df.ast==1)&(df.stl==1)&(df.blk==1))
show("exactly 2 of pts-reb-ast-stl-blk (2x5)", (df.pts==2)&(df.reb==2)&(df.ast==2)&(df.stl==2)&(df.blk==2))
show("5x5 (5+ in all five)", (df.pts>=5)&(df.reb>=5)&(df.ast>=5)&(df.stl>=5)&(df.blk>=5))
show("0 min with a stat", (df['min']==0)&((df.pts>0)|(df.tov>0)|(df.reb>0)|(df.pf>0)|(df.fga>0)))
show("0 min with a turnover", (df['min']==0)&(df.tov>0))
show("20+ FGA at 20% or worse", (df.fga>=20)&(df.fgm<=0.2*df.fga), "fga")
show("18+ missed shots", (df.fga-df.fgm>=18), "fga")
show("10+ FGM without a miss", (df.fgm>=10)&(df.fgm==df.fga), "fgm")
show("16+ FTM without a miss", (df.ftm>=16)&(df.ftm==df.fta), "ftm")
show("10+ FT missed", (df.fta-df.ftm>=10), "fta")
show("starter, 30+ min, 0 pts", (df.starter==1)&(df['min']>=30)&(df.pts==0), "min")
show("starter, 25+ min, 0 pts", (df.starter==1)&(df['min']>=25)&(df.pts==0), "min")
show("20+ min and nothing at all (pts reb ast stl blk tov fga)", (df['min']>=20)&(df.pts+df.reb+df.ast+df.stl+df.blk+df.tov+df.fga+df.fta==0), "min")
show("fouled out in 12 or fewer min", (df.pf>=6)&(df['min']<=12), "min", True)
show("10+ turnovers", (df.tov>=10), "tov")
show("0 pts with 10+ ast", (df.pts==0)&(df.ast>=10), "ast")
show("0 pts with 15+ reb", (df.pts==0)&(df.reb>=15), "reb")
show("40+ pts off the bench", (df.starter==0)&(df.pts>=40), "pts")
show("20+ reb off the bench", (df.starter==0)&(df.reb>=20), "reb")
